func DetectCrisis(text string) bool {
	normalized := strings.ToLower(strings.ReplaceAll(text, "ё", "е"))
	for _, marker := range crisisMarkers {
		if strings.Contains(normalized, strings.ReplaceAll(marker, "ё", "е")) {
			return true
		}
	}
	return false
}
